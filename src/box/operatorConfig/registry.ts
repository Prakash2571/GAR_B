/**
 * THE OPERATOR SETTING REGISTRY — the single declarative list of what an operator may change.
 *
 * WHAT IS DELIBERATELY *NOT* HERE, AND WHY THAT IS THE POINT
 *
 * `loadBoxConfig()` parses 131 fields. This registry has a deliberately small fraction of them. The
 * goal of this subsystem is to REDUCE operator complexity, not to move `.env` into a web form, so a
 * setting earns a place here only if an operator has a concrete reason to change it during a trading
 * day. Everything below stays deployment configuration and is read-only in the UI:
 *
 *   deployment capability  BOX_EXECUTION_MODE, BOX_LIVE_TRADING_ENABLED,
 *                          ZERODHA_/DHAN_LIVE_TRADING_ENABLED, BOX_SHADOW_MODE_ENABLED,
 *                          BOX_EXECUTION_COORDINATOR_ENABLED — a runtime control must never be able
 *                          to turn a paper deployment into a live-capable one
 *   reservation machinery  lock TTLs, renew intervals, clock-skew grace, uncertain-hold windows
 *   transport and pacing   broker min intervals, entry submit concurrency, every live timeout
 *   queue internals        chase ticks, queue model, liquidity haircut, tick size
 *   loops and metrics      monitor/persist/publish intervals, metric windows, timing persistence
 *   reconciliation         reconcile intervals, feed reconnect warm-up
 *   infrastructure         PORT, DATABASE_URL, pool sizing, Mongo export, proxies, broker API roots
 *
 * See `docs/OPERATOR_CONFIG_AUDIT.md` §6.8 for the full excluded list and the reasoning per group.
 *
 * SECRETS ARE STRUCTURALLY EXCLUDED
 *
 * `assertNoSensitiveKeys()` below cross-checks every `envVar` against `EXPLICIT_ENV_CLASS` in
 * `src/env/secrets.ts` — the taxonomy the codebase already uses — and throws if a `secret` or
 * `identity` variable is ever registered. A test calls it, so the guard cannot rot into a comment.
 *
 * DEFAULTS MIRROR `loadBoxConfig()` EXACTLY
 *
 * Every `codeDefault` here is the same literal `src/box/config.ts` uses. They are kept honest by
 * `tests/operatorConfig/registryParity.test.mjs`, which reads the loader's source and compares, so a
 * future change to one side cannot silently drift from the other. That parity is what makes "first
 * deployment behaves exactly as before" true rather than hoped for.
 */

