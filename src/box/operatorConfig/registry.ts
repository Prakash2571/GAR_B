/** The persisted `box_settings.key` for a domain key. Stable, snake_case, decoupled from TS names. */
export function persistedKeyFor(key: string): string {
  return key.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
}

/**
 * THE SECURITY GUARD: no credential may ever become a runtime setting.
 *
 * Cross-checks every registered `envVar` against the codebase's existing classification in
 * `src/env/secrets.ts`. Takes the class lookup as a parameter rather than importing it, so this
 * module stays free of every dependency and can be exercised directly from source by the test
 * harness — the same property that makes it safe to assert on.
 *
 * Throws rather than returning a list: a secret reaching a configuration API is not a warning.
 */
export function assertNoSensitiveKeys(
  classOf: (envVar: string) => "secret" | "identity" | "config" | undefined,
): void {
  const offenders: string[] = [];
  for (const spec of OPERATOR_SETTINGS) {
    const cls = classOf(spec.envVar);
    if (cls === "secret" || cls === "identity") offenders.push(`${spec.key} (${spec.envVar}: ${cls})`);
  }
  if (offenders.length > 0) {
    throw new Error(
      `[operatorConfig] refusing to expose non-config environment variables through the runtime ` +
        `configuration API: ${offenders.join(", ")}`,
    );
  }
}

/** Every setting whose specification says it must never be writable. */
export function readOnlyKeys(): readonly string[] {
  return OPERATOR_SETTINGS.filter((s) => s.policy === "RESTART_REQUIRED").map((s) => s.key);
}
